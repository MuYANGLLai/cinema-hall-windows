package com.cinemahall.core.session

import kotlin.math.abs

/**
 * 两端单调时钟的偏差与往返延迟估计（《技术方案评审》§6.1）。
 *
 * ── 报文从哪来（这里有个容易找错的地方）────────────────────────────────────
 * §6.1 的算式要三个时刻：`t1` 发起方发出时刻、`t2` 对端当前时钟、`t4` 发起方收到时刻。
 * §5.3 的消息表里**没有专门的探测消息** —— 但也不需要新增：
 *
 *  - `t1` 是**从端自己**记录的「我这一刻发了 `cinema.sync_ack`」。它就在同一时基
 *    （注入的 `MonotonicClock`，Android 上是 `SystemClock.elapsedRealtime()`）上，
 *    所以根本不需要对端回传（信封的 `sentAtMs` 走的是同一个时基，§5.1）。
 *  - `t2` 是房主那条 `cinema.heartbeat` 的 `senderClockMs`（§5.3 原本就有这个字段）。
 *  - `t4` 是从端收到那条 heartbeat 的时刻。
 *
 * 于是「探测」和「应答」正好落在既有的两条消息上，一个字节都不用加：
 * **从端发 `sync_ack`（t1）→ 房主立刻回 `heartbeat`（t2）→ 从端收到（t4）**。
 * 这条链路同时满足 §6.4 对 heartbeat 那句「重设锚点（这同时也在持续刷新
 * rttHalf 与时钟 offset）」—— 刷新正是发生在这里。
 *
 * ── 为什么只采用 RTT 最小的那个样本（§6.1 的 min-RTT 滤波）─────────────────
 * 上式里的 `rtt/2` 把往返当成**对称**的。RTT 越大，前半段与后半段越可能不对称
 * （排队、重传、TCP 层握手），这个假设就越不成立。而 RTT 最小的一次恰恰是
 * 最接近「只吃物理延迟、没有排队」的那次 —— 所以它给出的 offset 最准。
 * 取「窗口内最小 RTT 的那个 offset」，而不是「所有样本的平均」，正是这个道理：
 * 平均会被少数几次大 RTT 的坏样本拖偏，而最小值只会被更好的样本替换。
 *
 * **不采用中位数 / 累积平均**：它们在链路抖动时给出的是一个「来回晃但不跳」的值，
 * 看起来更稳，其实每一刻都不准 —— 而 §6.2 的锚点补偿只关心「这一刻的单向延迟」。
 *
 * 那段话针对的是**单向延迟**（[rttHalfMs]）：它要逐条算。而**偏差**（[offsetMs]）不是
 * 一回事 —— 它是个慢变量，抖的是「量它的过程」。2026-10-12 的真机缺陷正出在这里：
 * 偏差的跳变会一路变成目标位置的跳变。所以两者现在分开处理：延迟照旧取 min-RTT 的
 * 原始值，偏差做限速跟随（见 [slewOffset]）。
 */
class ClockSync(private val window: Int = 8) {

    /** 一次往返的观测结果。 */
    data class Sample(
        /** 往返延迟 `t4 − t1`。 */
        val rttMs: Long,
        /** 对端时钟 − 本地时钟，`t2 − (t1 + rtt/2)`。 */
        val offsetMs: Long,
    )

    private val samples = ArrayDeque<Sample>()

    /** 窗口内 RTT 最小的样本。null 表示还没量到过一次有效往返。 */
    private var best: Sample? = null

    /**
     * **用于补偿的**偏差：对 [best] 的偏差做限速跟随之后的当前值（见 [slewOffset]）。
     *
     * 与 [best] 分开存而不是就地改 `best`：`best` 还要供 [rttMs] / [rttHalfMs] 用，
     * 而那两栏的语义是「窗口里最走运的那次往返」，必须保持原始值（诊断页与
     * `cinema.sync_ack.rttMs` 都按这个口径读）。
     */
    private var steadyOffsetMs: Long? = null

    /**
     * 单向延迟估计（§6.1），§6.2 的锚点补偿就用它。
     *
     * 还没量过时返回 0 —— 这不是「猜一个」，而是「先不补偿」。宁可第一秒落后
     * 半个 RTT，也不要拿一个编出来的数字去锚定：那会让第一帧就跳一下。
     */
    val rttHalfMs: Long get() = (best?.rttMs ?: 0L) / 2

    /** 完整往返延迟，诊断页与 `cinema.sync_ack.rttMs` 用它。 */
    val rttMs: Long get() = best?.rttMs ?: 0L

    /**
     * 对端时钟 − 本地时钟（§9.3 的「时钟 offset」）。
     *
     * 这是**限速跟随之后**的值，也就是 [flightMsOf] 真正拿去补偿的那个 —— 想看点名之前
     * 的原始估计（诊断页用它量抖动幅度）读 [rawOffsetMs]。
     */
    val offsetMs: Long get() = steadyOffsetMs ?: 0L

    /** 窗口内 min-RTT 样本直接给出的偏差，**未**做限速跟随。只用于诊断与单测。 */
    val rawOffsetMs: Long get() = best?.offsetMs ?: 0L

    val hasEstimate: Boolean get() = best != null

    /**
     * **这条消息实际飞了多久**（本机毫秒）—— §6.2 的锚点补偿要的正是它（2026-10-12 修）。
     *
     * ── 为什么不能拿 [rttHalfMs] 代替 ──────────────────────────────────────────
     * `rttHalfMs` 是**窗口内最小 RTT** 的一半：它是「这一段时间里最走运的那一次」，
     * 而锚点补偿要回答的是「**这一刻**这条消息飞了多久」。两者在中继路径上差得很远，
     * 差值直接变成目标位置的偏置 —— 而偏置超过 `hardDriftMs`(300ms) 时，从端每收到
     * 一条心跳就硬 seek 一次（画面与声音一起断）。真机报的正是这一条：
     * 「P2P 直连不卡，启用强制中继从端就卡」。
     *
     * 三个来源都会让最小半 RTT 明显偏小：
     *  ① 中继 RTT 本来就大且抖（排队、重传），最小值只反映最好的一次；
     *  ② 用户**切换强制中继**时窗口里还留着切换前的 P2P 样本（RTT 个位数毫秒）；
     *  ③ 定时心跳与「收到 `sync_ack` 立刻回」的那条心跳走的延迟并不相同。
     *
     * ── 算式 ────────────────────────────────────────────────────────────────
     * `对端发这条消息时的时钟 + offset = 本机此刻的时钟`，两边相减就是飞行时间。
     * `offset` 取 [offsetMs]（限速跟随之后的值）：**它**才是那个该稳定的量，
     * 而这里要的正是「稳定」，否则每换一个 min-RTT 样本，飞行时间就整体平移一次 ——
     * 平移量直接变成目标位置的偏置，正是这一条要治的症状。
     *
     * 返回 null = 还没量到时钟偏差（[hasEstimate] 为 false）：那时换算没有意义，
     * 调用方退回 [rttHalfMs]（它此刻是 0，也就是「先不补偿」）。
     */
    fun flightMsOf(senderClockMs: Long, nowLocalMs: Long): Long? {
        val offset = steadyOffsetMs ?: return null
        val flight = (nowLocalMs + offset) - senderClockMs
        // 夹进 0..MAX_FLIGHT_MS。负值只可能来自「对端时钟比我们以为的慢」（它重启过、
        // 而 offset 还是旧的）；过大则可能是 offset 坏了，或这条消息真的卡了很久。
        // 两种都不该让目标位置凭空跳一大截 —— 那正好是这一条要治的症状。
        return flight.coerceIn(0L, MAX_FLIGHT_MS)
    }

    val sampleCount: Int get() = samples.size

    /**
     * 记一次往返。返回被采纳的样本；`t4 < t1` 这种不可能的组合返回 null 并丢弃。
     *
     * ── `t4 < t1` 为什么必须挡掉，而不是取绝对值 ────────────────────────────
     * 它只可能来自「用错了时基」（拿墙上钟和单调钟混算）。取绝对值会把这个
     * 编程错误变成一个看起来正常的正数继续参与滤波，真正的病因就被埋掉了。
     * 丢弃 + 保持上一次的好估计，是这里唯一不自欺的处置。
     */
    fun onRoundTrip(t1: Long, t2: Long, t4: Long): Sample? {
        val rtt = t4 - t1
        if (rtt < 0) return null

        val sample = Sample(rttMs = rtt, offsetMs = t2 - (t1 + rtt / 2))
        samples.addLast(sample)
        while (samples.size > window) samples.removeFirst()

        // 每来一个样本就重算一次最小值，而不是「更小才替换」：窗口滑动时
        // 被淘汰的可能正是当前的最小值，那时必须退回到次小值。
        // `minByOrNull` 返回**第一个**最小值 —— RTT 相同时保留更早的那个，
        // 让估计不会因为等值样本反复横跳。
        best = samples.minByOrNull { it.rttMs }
        slewOffset()
        return sample
    }

    /**
     * 把「用于补偿的偏差」朝 [best] 挪一步，**每步最多 [MAX_OFFSET_STEP_MS]**（2026-10-12 真机缺陷）。
     *
     * ── 症状：强制中继下从端「一会卡一会不卡」，从端在 WiFi 下明显缓解 ──────────
     * 真机报的正是这两条。这一段链路里唯一会随网络波动的东西就是这个偏差：
     *
     *  ① `best` 是**窗口内 RTT 最小**的那个样本，而窗口在滑动。当前的最小值被挤出窗口时，
     *     `best` 会换成另一个样本，它的 `offset` 与上一个相差「两次路径不对称度之差的一半」——
     *     中继 + 蜂窝下这个差值能到几十上百毫秒，WiFi 下只有几毫秒。**这就是「网络波动」**。
     *  ② 这个偏差**直接**变成目标位置的偏置（[flightMsOf]），于是每收到一条心跳，目标位置
     *     就整体平移一次，漂移跟着平移一次。
     *  ③ 漂移一越过 80ms 就进「变速追赶」档、越过 300ms 就硬 seek。从端于是每 2.5 秒
     *     （一个心跳周期）变一次速或跳一次画面 —— 画面与声音一起顿。
     *
     * ── 为什么限速是对的，而不是「把估计做得更准一点」──────────────────────────
     * 偏差是**慢变量**：两端都跟着系统时钟走，真实偏差只以 ppm 级的速率漂移。会抖的从来
     * 不是它，是**量它的过程**（排队、重传、路径不对称）。所以这里不需要更聪明的滤波，
     * 只需要「不要相信单次测量的跳变」：一次最多挪 40ms（软阈值的一半）——
     * 于是**单次重锚注入的漂移永远不可能自己越过「什么都不做」那一档**。
     * 这是这条限速要买的性质，也是单测直接钉住的那条。
     *
     * 挪得慢不会让同步变差：漂移是「本机位置 − 目标位置」，目标慢慢挪、本机慢慢跟，
     * 两者之差始终只有这一步的大小；而**真实**的两端位置差在任何时刻都等于偏差估计的
     * 误差本身 —— 限速不改变它的收敛目标，只去掉路上的台阶。
     *
     * ── 「限速会不会让真实变化跟不上」─────────────────────────────────────────
     * 唯一能让真实偏差一次跳掉几百毫秒的事件是**对端重启**（它的单调钟归零，新偏差是
     * 它的开机时长）。那时差值远超 [REBASE_OFFSET_MS]，直接采纳新值：限速只对付抖动，
     * 不对付换钟。
     */
    private fun slewOffset() {
        val raw = best?.offsetMs
        if (raw == null) {
            steadyOffsetMs = null
            return
        }
        val prev = steadyOffsetMs
        steadyOffsetMs = if (prev == null || abs(raw - prev) > REBASE_OFFSET_MS) {
            // 第一个样本直接采纳：不采纳就没有任何补偿可用，首帧会稳定落后半个 RTT。
            raw
        } else {
            prev + (raw - prev).coerceIn(-MAX_OFFSET_STEP_MS, MAX_OFFSET_STEP_MS)
        }
    }

    /** 换链路 / 换对端时清空：上一轮的 RTT 对这条新路径没有任何参考价值。 */
    fun reset() {
        samples.clear()
        best = null
        steadyOffsetMs = null
    }

    companion object {
        /**
         * [flightMsOf] 的补偿上限。
         *
         * ── 为什么要有上限，以及为什么取这个量级 ────────────────────────────────
         * 算出来的飞行时间有三种可能：真的飞了这么久、`offset` 已经坏了（对端重启过
         * 而我们还留着旧偏差）、或者这条消息本来就是一条积压了很久的旧消息。
         * 后两种下这个数字会大到几百上千毫秒，而它**直接变成目标位置的偏置** ——
         * 偏置一大，从端立刻硬 seek 一次，正好是这一条要治的症状。
         *
         * 取 2000ms（略小于 [CinemaSyncConfig.heartbeatIntervalMs] 的 2500ms）：
         * 消息飞得比一个心跳周期还久，它描述的就不再是「这一刻」，再往上补只是在
         * 拿一个坏样本去锚定。夹住而不是丢弃 —— 丢弃会让时间轴停在旧锚点上，
         * 位置就此落后一段；夹住只是「少补一点」，曲线仍是连续的。
         */
        const val MAX_FLIGHT_MS = 2_000L

        /**
         * 每次重锚最多允许把补偿挪多少毫秒（2026-10-12 真机缺陷）。
         *
         * 取 40 = `CinemaSyncConfig.softDriftMs`(80) 的一半。理由不是「40 这个数字好看」，
         * 而是它买到的**性质**：单次重锚注入的漂移最多 40ms，而 40 < 80 ——
         * 「什么都不做」那一档的边界。于是任何一次网络抖动都不可能自己把从端推进
         * 「变速追赶」，更不可能推进硬 seek。
         *
         * 取一半而不是贴着 80：漂移在两次重锚之间还会被本机位置自身的读数抖动、
         * 以及上一次追赶的余量占用一点，留一半给它们。
         *
         * 它**不**改 `CinemaSyncConfig`：那里是 §6.8 的真机可调参数表（评审文档禁改），
         * 而这个数是「不许越过软阈值」这条性质的推论，不是可调项。
         */
        const val MAX_OFFSET_STEP_MS = 40L

        /**
         * 偏差一次性跳这么多毫秒就认定「换了一只时钟」，不再限速跟随。
         *
         * 真实偏差只可能因为**对端重启**（单调钟归零，新偏差 = 它的开机时长）跳掉
         * 几百毫秒以上。路径不对称再坏也造不出 1 秒的差值（那要求 RTT 大于 2 秒
         * 且延迟全压在一侧）—— 所以这个门槛能把「换钟」和「抖得厉害」分开。
         */
        const val REBASE_OFFSET_MS = 1_000L
    }
}
